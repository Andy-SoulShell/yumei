export const CREATOR_TEMPLATES: readonly CreatorTemplate[] = definitions.map(
  ([
    id,
    gender,
    style,
    name,
    age,
    vibe,
    hairstyle,
    hair,
    eyes,
    bodytype,
    details,
    personality,
    interests,
  ]) => ({
    id,
    gender,
    style,
    name,
    personality,
    interests,
    imageUrl:
      style === "anime"
        ? `/character-options/creator/${gender}/anime/ethnicity/${vibe}.webp`
        : `/character-options/creator/templates/${id}.webp`,
    selection: {
      gender,
      style,
      age,
      details,
      options: {
        templates: id,
        ethnicity: vibe,
        hairstyle,
        hair,
        eyes,
        bodytype,
        skin: "light",
        ...(gender === "female" ? { breast: "medium", butt: "medium" } : {}),
      },
    },
  })
);

/** 按稳定标识查找向导模板，不读取首页预设。 */
export function getCreatorTemplate(id: string) {
  return CREATOR_TEMPLATES.find(template => template.id === id);
}
