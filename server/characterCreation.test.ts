import { beforeEach, describe, expect, it, vi } from "vitest";
import { girlfriendRouter } from "./routers/girlfriend";
import { createWithPortrait } from "./characterPortrait";
import {
  createGirlfriend,
  getUserGirlfriends,
} from "./repositories/companions";
import { putStagedMedia } from "./managedMedia";
import { queueMediaDeletion } from "./mediaCleanup";
import { isBillingEnforced } from "./billing";
vi.mock("./characterPortrait", () => ({ createWithPortrait: vi.fn() }));
vi.mock("./billing", () => ({
  getTierLimits: vi.fn(async () => ({ limits: { maxGirlfriends: 1 } })),
  isBillingEnforced: vi.fn(),
}));
vi.mock("./repositories/companions", () => ({
  createGirlfriend: vi.fn(),
  getUserGirlfriends: vi.fn(),
}));
vi.mock("./repositories/intimacy", () => ({ getIntimacyInfo: vi.fn() }));
vi.mock("./characterPresets", () => ({
  readPresetReference: vi.fn(),
  readDefaultReference: vi.fn(),
}));
vi.mock("./managedMedia", () => ({ putStagedMedia: vi.fn() }));
vi.mock("./mediaCleanup", () => ({
  queueMediaDeletion: vi.fn(),
  flushMediaDeletions: vi.fn(),
}));
const png = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10, 0]);
const user = { id: "portrait-owner", birthDate: "1999-01-01" };
const caller = girlfriendRouter.createCaller({ user, req: {}, res: {} } as any);
const input = {
  name: "小雨",
  personality: "温柔",
  appearance: "成年，棕色马尾",
  generatePortrait: true as const,
};
beforeEach(() => {
  vi.resetAllMocks();
  vi.mocked(isBillingEnforced).mockReturnValue(false);
  vi.mocked(createWithPortrait).mockImplementation(
    async (_user, _appearance, save) => save(png)
  );
  vi.mocked(putStagedMedia).mockImplementation(async (_user, key) => ({
    key,
    url: `http://app/files/${key}`,
  }));
  vi.mocked(createGirlfriend).mockImplementation(
    async data => ({ id: 1, ...data }) as any
  );
  vi.mocked(queueMediaDeletion).mockResolvedValue();
});
describe("text-based character creation API", () => {
  it("stores generated bytes as the character's actual identity image", async () => {
    const result = await caller.create(input);
    expect(createWithPortrait).toHaveBeenCalledWith(
      user,
      input.appearance,
      expect.any(Function)
    );
    expect(putStagedMedia).toHaveBeenCalledWith(
      user.id,
      expect.stringMatching(/^girlfriend-portrait-owner-.*\.png$/),
      png,
      "image/png"
    );
    expect(result.referenceImageUrl).toMatch(/^http:\/\/app\/files\//);
    expect(createGirlfriend).toHaveBeenCalledWith(
      expect.objectContaining({
        appearance: input.appearance,
        userId: user.id,
      }),
      null
    );
  });
  it("rejects ambiguous requests that mix text generation with a preset or upload", async () => {
    for (const extra of [
      { presetId: "momoka" },
      { referenceImageBase64: "abc", referenceImageMimeType: "image/png" },
      { referenceImageMimeType: "image/png" },
    ])
      await expect(
        caller.create({ ...input, ...extra } as any)
      ).rejects.toThrow();
    expect(createWithPortrait).not.toHaveBeenCalled();
  });
  it("checks the plan's character limit before calling a paid provider", async () => {
    vi.mocked(isBillingEnforced).mockReturnValue(true);
    vi.mocked(getUserGirlfriends).mockResolvedValue([{ id: 8 }] as any);
    await expect(caller.create(input)).rejects.toThrow("UPGRADE_REQUIRED");
    expect(createWithPortrait).not.toHaveBeenCalled();
  });
  it("queues the generated image for cleanup if saving fails", async () => {
    vi.mocked(createGirlfriend).mockRejectedValue(new Error("save failed"));
    await expect(caller.create(input)).rejects.toThrow("save failed");
    expect(queueMediaDeletion).toHaveBeenCalledWith(user.id, [
      expect.stringMatching(/^girlfriend-portrait-owner-/),
    ]);
  });
});
